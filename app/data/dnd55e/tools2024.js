function expandAbilities(text) {
  let out = text
  // «атак, использующих ИНТ» — винительный падеж.
  for (const [abbr, word] of Object.entries(ABILITY_ACCUSATIVE)) {
    out = out.replace(new RegExp('(использующ[а-яё]+ )' + abbr + '(?![А-Яа-яЁё])', 'g'), '$1' + word)
  }
  // «спасбросков МУД», «броски ХАР», «проверке ИНТ» — родительный.
  for (const [abbr, word] of Object.entries(ABILITY_GENITIVE)) {
    out = out.replace(new RegExp('(^|[^А-Яа-яЁё])' + abbr + '(?![А-Яа-яЁё])', 'g'), '$1' + word)
  }
  return out
}

