function defaultQuick(item) {
  if (GENERAL_QUICK[item.id]) return GENERAL_QUICK[item.id]

  if (item.category === 'actions') {
    return [
      { label: 'Стоимость', value: '1 действие' },
      { label: 'Разрешение', value: ACTION_RESOLUTION[item.id] || 'По описанию' }
    ]
  }

  if (item.category === 'skills') {
    const ability = SKILL_ABILITIES[item.id] || 'По решению Мастера'
    return [
      { label: 'Характеристика', value: ability },
      { label: 'Проверка', value: `${ability} (${item.title})` }
    ]
  }

  if (item.category === 'areas-of-effect') return [{ label: 'Форма', value: item.title }, { label: 'Преграда', value: 'Полное укрытие' }]
  if (item.category === 'conditions') return [{ label: 'Тип', value: 'Состояние' }, { label: 'Сложение', value: item.id === 'exhaustion-phb' ? 'Уровни складываются' : 'Не складывается само с собой' }]
  if (item.category === 'abilities') return [{ label: 'Тип', value: 'Характеристика' }, { label: 'Модификатор', value: '(значение − 10) / 2, вниз' }]
  if (item.category === 'weapon-masteries') return [{ label: 'Тип', value: 'Оружейный приём' }, { label: 'Срабатывание', value: MASTERY_TRIGGERS[item.id] || 'При атаке' }]
  if (item.category === 'attitudes') return [{ label: 'Проверка', value: 'Действие Влияние' }, { label: 'Эффект', value: item.id === 'friendly-phb' ? 'Преимущество' : 'Помеха' }]
  if (item.category === 'weapon-properties') return [{ label: 'Тип', value: 'Свойство оружия' }, { label: 'Применение', value: 'По условиям атаки' }]
  if (item.category === 'traps') return [{ label: 'Тип', value: 'Ловушка' }, { label: 'Этапы', value: 'Обнаружение · обезвреживание · эффект' }]
  if (item.category === 'magic-items') return [{ label: 'Тип', value: 'Магический предмет' }, { label: 'Применение', value: 'По описанию предмета' }]
  if (item.category === 'magical-contagions') return [{ label: 'Тип', value: 'Магическое заражение' }, { label: 'Защита', value: 'Спасброски и лечение' }]
  if (item.category === 'hazards') return [{ label: 'Тип', value: 'Опасность' }, { label: 'Разрешение', value: 'По описанию воздействия' }]
  if (item.category === 'treasures') return [{ label: 'Тип', value: 'Сокровище' }, { label: 'Оценка', value: 'Стоимость и доступность' }]
  if (item.category === 'environmental-effects') return [{ label: 'Тип', value: 'Эффект среды' }, { label: 'Защита', value: 'Снаряжение, проверка или спасбросок' }]
  return [{ label: 'Тип', value: 'Термин правил' }, { label: 'Применение', value: 'По описанию' }]
}

export function structureGlossaryRule(item, details) {
  const coreSections = details.sections?.length
    ? details.sections
    : [{
        title: CATEGORY_SECTION_TITLES[item.category] || 'Как работает',
        kind: 'rule',
        paragraphs: details.paragraphs
      }]

  return {
    quick: details.quick?.length ? details.quick : defaultQuick(item),
    sections: [
      ...coreSections.map(section => ({ kind: 'rule', ...section })),
      ...buildGlossaryGuidance(item, details)
    ]
  }
}

