export const GUILD_FILTERS = ['Все гильдии', ...new Set(GUILDS.map(guild => guild.category))]
export const guildBySlug = slug => GUILDS.find(guild => guild.slug === slug)
export const normalizeGuildSearch = value => String(value || '').toLocaleLowerCase('ru-RU').replaceAll('ё', 'е').replace(/[’']/g, '')
export function guildMatches(guild, query, category = 'Все гильдии') {
  const text = normalizeGuildSearch([guild.name, guild.location, guild.place, guild.summary, guild.ship?.name, ...guild.members.flatMap(member => [member.name, member.description])].join(' '))
  return (category === 'Все гильдии' || guild.category === category) && text.includes(normalizeGuildSearch(query).trim())
}
