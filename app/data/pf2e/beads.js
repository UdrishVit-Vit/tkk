const TIER_STATS = {
  uncommon: { level: 5, dc: 20, rarity: 'необычное' },
  rare: { level: 9, dc: 26, rarity: 'редкое' },
  veryRare: { level: 13, dc: 31, rarity: 'редкое' }
}

const SOURCE = Object.fromEntries(BEADS_5E.map(b => [b.num, b]))

function bead(num, powers, extra = {}) {
  const src = SOURCE[num]
  const stats = TIER_STATS[src.tier]
  return {
    num,
    id: src.id,
    title: src.title,
    tier: src.tier,
    level: stats.level,
    dc: stats.dc,
    traits: [stats.rarity, 'магический', 'вложение', ...(extra.traits || [])],
    flavor: src.flavor,
    sig: src.sig,
    charges: extra.charges || src.charges,
    powers
  }
}

const trait = (name, text, extra = {}) => ({ name, text, ...extra })
const act = (name, actions, cost, text, extra = {}) => ({ name, actions, cost, text, ...extra })
const curse = (name, text) => ({ name, text, curse: true })

