// Бусины Эноа для Pathfinder 2e. Предыстория и сигнатура 4к4 общие с D&D
// (beads5e.js), механика переписана под PF2e:
// - редкость бусины задаёт уровень предмета и Сл: необычная — 5 уровень, Сл 20;
//   редкая — 9 уровень, Сл 26; очень редкая — 13 уровень, Сл 31 (Сл по уровню);
//   там, где автор ставил Сл выше или ниже Сл опознания, разница сохранена;
// - настройка → вложение, преимущество → бонус обстоятельств +2,
//   помеха → штраф, истощение → «Утомлённый», вдохновение → очко героя;
// - actions — стоимость активации: '1' | '2' | '3' | 'reaction' | 'free' или время.
//
// Баланс сверен с ориентирами PF2e:
// - круг заклинания из бусины — как у палочки того же уровня: 5 ур. ≈ 2 круг,
//   9 ур. ≈ 4 круг, 13 ур. ≈ 6 круг (5 круг, если активация даёт что-то ещё);
// - постоянное сопротивление — как у кольца сопротивления энергии: 5 до 10 уровня;
// - постоянный бонус к навыку — бонус предмета +1 до 9 уровня; бонус обстоятельств +2
//   только в узкой ситуации («в море», «против очарования»);
// - урон активации за 1 заряд — около 5к6 на 9 уровне, все заряды разом — как заклинание круга;
// - тяжёлые состояния снимаются только новым спасброском, ход у врага не отнимается.

