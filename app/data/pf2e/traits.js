export function pf2eTraitHint(trait = '') {
  // Traits carry their value inline ("смертельное к8", "дальность 60 футов");
  // look the base word up so the tooltip still resolves.
  const base = String(trait).split(' ')[0].toLowerCase()
  return PF2E_ALL_TRAITS[String(trait).toLowerCase()] || PF2E_ALL_TRAITS[base] || ''
}
