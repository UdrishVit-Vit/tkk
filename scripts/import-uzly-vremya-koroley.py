def paragraphs(path):
    """Абзацы документа: текст и признак сплошного курсива."""
    root = ET.fromstring(zipfile.ZipFile(path).read('word/document.xml'))
    for p in root.find(W + 'body').iter(W + 'p'):
        text = ''
        italic = runs = 0
        for run in p.iter(W + 'r'):
            piece = ''.join(node.text or '' for node in run.iter(W + 't'))
            if piece.strip():
                runs += 1
                props = run.find(W + 'rPr')
                if props is not None and props.find(W + 'i') is not None:
                    italic += 1
            text += piece
        text = re.sub(r'\s+', ' ', text).replace('­', '').strip()
        for wrong, right in NAMES:
            text = text.replace(wrong, right)
        if text:
            yield text, bool(runs and italic == runs)


def split_speech(text):
    """Разносит склеенные реплики по абзацам."""
    return [piece.strip() for piece in GLUED.split(text) if piece.strip()]


# Подзаголовки нумеруются римскими, как в литературной редакции «Огней»:
# «I. Тень в полдень», «II. Имени у меня не было».
ROMAN = [
    (100, 'C'), (90, 'XC'), (50, 'L'), (40, 'XL'),
    (10, 'X'), (9, 'IX'), (5, 'V'), (4, 'IV'), (1, 'I'),
]


def roman(number):
    out = ''
    for value, sign in ROMAN:
        while number >= value:
            out += sign
            number -= value
    return out


def plain(text):
    """Строка без апострофов: в рукописи они то прямые, то типографские."""
    return re.sub(APOSTROPHES, '', text)


def blocks_of(items, scenes):
    """Абзацы главы — в блоки страницы: заголовок сцены, проза, легенда."""
    blocks = []
    prose = []
    pending = list(scenes)

    def flush():
        if prose:
            blocks.append({'type': 'prose', 'paragraphs': list(prose)})
            prose.clear()

    def open_scene(piece):
        # Начало сцены ищется по куску после переверстки: в рукописи он часто
        # склеен с предыдущей репликой и отдельным абзацем не стоит. Апострофы
        # в рукописи двух видов вперемешку, поэтому сверяем без них.
        if pending and plain(piece).startswith(plain(pending[0][0])):
            flush()
            blocks.append({'type': 'heading',
                           'text': '%s. %s' % (roman(len(scenes) - len(pending) + 1),
                                               pending.pop(0)[1])})

    for text, italic in items:
        if DIVIDER.match(text):
            # Названная сцена сама отбивает текст; безымянную отбиваем ромбом.
            if not scenes:
                flush()
                if blocks and blocks[-1]['type'] != 'divider':
                    blocks.append({'type': 'divider'})
            continue
        pieces = split_speech(text)
        if italic:
            if pieces:
                open_scene(pieces[0])
            flush()
            blocks.append({'type': 'verse', 'paragraphs': pieces})
            continue
        for piece in pieces:
            open_scene(piece)
            prose.append(piece)
    flush()
    while blocks and blocks[-1]['type'] == 'divider':
        blocks.pop()
    if pending:
        raise SystemExit('Не найдены начала сцен: ' + '; '.join(a for a, _ in pending))
    return blocks


def parse(path):
    items = list(paragraphs(path))
    chapters = []
    epigraph = []
    current = None

    for text, italic in items:
        match = CHAPTER_MARK.search(text)
        if match:
            head = text[:match.start()].strip()
            if head and current is not None:
                current['items'].append((head, italic))
            chapters.append({'number': int(match.group(1)), 'items': []})
            current = chapters[-1]
            tail = text[match.end():].strip()
            if tail:
                current['items'].append((tail, italic))
            continue
        if current is None:
            # До первой главы стоит эпиграф книги.
            if italic:
                epigraph.append(text)
            continue
        current['items'].append((text, italic))

    return epigraph, chapters


def main():
    if len(sys.argv) < 2:
        raise SystemExit('Укажите путь к docx первым аргументом.')

    path = sys.argv[1]
    epigraph, chapters = parse(path)
    if len(chapters) != len(CHAPTERS):
        found = ', '.join(str(chapter['number']) for chapter in chapters)
        raise SystemExit('Ожидалось %d глав, найдено %d (%s).' % (len(CHAPTERS), len(chapters), found))

    payload = {
        'source': Path(path).name,
        'epigraph': epigraph,
        'chapters': [
            {
                'slug': CHAPTERS[index][0],
                'number': index + 1,
                'title': CHAPTERS[index][1],
                'blocks': blocks_of(chapter['items'], SCENES.get(CHAPTERS[index][0], [])),
            }
            for index, chapter in enumerate(chapters)
        ],
    }

    OUT_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

    counts = []
    for chapter in payload['chapters']:
        text = sum(len(p) for block in chapter['blocks'] for p in block.get('paragraphs', []))
        paragraph_count = sum(len(block.get('paragraphs', [])) for block in chapter['blocks'])
        scenes = sum(1 for block in chapter['blocks'] if block['type'] in ('divider', 'heading'))
        counts.append((chapter['number'], chapter['title'], paragraph_count, scenes, text))
    for number, title, paragraph_count, scenes, text in counts:
        print('%2d. %-16s абзацев %4d, сцен %2d, знаков %6d' % (number, title, paragraph_count, scenes, text))
    print('Эпиграф: %d абзац(ев). Записано: %s' % (len(epigraph), OUT_PATH.relative_to(ROOT)))


if __name__ == '__main__':
    main()
