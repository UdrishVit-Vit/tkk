import assert from 'node:assert/strict'
import {workingYearName as name,YEAR_IMAGES,YEAR_ASPECTS,YEAR_NAME_PERIOD,HISTORY_REFERENCE} from '../app/data/yearNaming.js'
assert.equal(YEAR_IMAGES.length,15)
assert.equal(YEAR_ASPECTS.length,13)
assert.equal(YEAR_NAME_PERIOD,195)
const circle=Array.from({length:YEAR_NAME_PERIOD},(_,i)=>name(i))
assert.equal(new Set(circle.map(x=>x.name)).size,195)
assert.equal(new Set(circle.map(x=>x.image.id+':'+x.aspect.id)).size,15*13)
for(const expected of ['Огненная Птица','Лазурный Каш','Кристальная Сова','Летящий Бук','Коралловый Перепелятник','Лазуритовый Бык','Рубиновая Лягушка','Лазурный Бык']) assert(circle.some(x=>x.name===expected),expected)
assert.equal(circle.find(x=>x.name==='Огненная Птица').yearLabel,'Огненной Птицы')
assert.equal(circle.find(x=>x.name==='Кристальная Сова').yearLabel,'Кристальной Совы')
assert.equal(circle.find(x=>x.name==='Рубиновая Лягушка').yearLabel,'Рубиновой Лягушки')
assert.equal(circle.find(x=>x.name==='Коралловый Перепелятник').yearLabel,'Кораллового Перепелятника')
assert.equal(name(0).name,'Пепельный Симург')
assert.equal(name(2).name,'Серебряный Аюр')
assert(!YEAR_IMAGES.some(image=>image.name==='Олень'))
assert(!YEAR_ASPECTS.some(aspect=>aspect.m==='Синий'))
assert.equal(name(5).name,'Огненный Левиафан')
for(let year=0;year<195;year++) assert.equal(name(year+195).name,name(year).name)
assert.equal(name(829).name,'Лазуритовый Журавль')
assert.equal(name(829).round,5)
assert.equal(name(829).position,50)
assert.equal(name(829).year,830)
assert.equal(HISTORY_REFERENCE.afterSplit-HISTORY_REFERENCE.afterEmbrace,HISTORY_REFERENCE.embraceAfterSplit)
assert(name(1000000))
assert.equal(name(-1),null)
assert.equal(name(1.5),null)
assert.equal(name(1000001),null)
assert(!circle.some(x=>x.name==='Красный Варан'))
console.log('Expanded cycle checks passed: all 195 pairs, eight requested names, feminine grammar, rollover and long chronology.')
